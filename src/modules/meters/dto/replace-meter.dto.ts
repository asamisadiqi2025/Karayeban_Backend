import {
  IsDateString,
  IsNotEmpty,
  IsNumber,
  IsOptional,
  IsString,
  MaxLength,
  Min,
  MinLength,
} from 'class-validator';

// تعویضِ «کنتورِ فیزیکی» یک دوکان (سوخته/خراب → یک دستگاهِ جدید می‌خرند و نصب می‌کنند).
// کنتورِ قدیمی غیرفعال می‌شود (با سابقهٔ کاملش: بل‌هایش با همان meterId می‌مانند) و یک کنتورِ جدید برای همان
// دوکان ساخته می‌شود؛ بل‌های بعدی روی کنتورِ جدید می‌نشینند.
//
// دو عددِ «کاملاً جدا» که نباید با هم قاطی شوند:
//   oldMeterFinalReading   → آخرین عددِ «کنتورِ خراب» (برای بستنِ حسابِ دستگاهِ قدیمی)
//   newMeterInitialReading → عددی که «کنتورِ جدید» هنگامِ نصب نشان می‌دهد (می‌تواند ۰ یا هر عددِ دیگر باشد)
export class ReplaceMeterDto {
  // سریالِ دستگاهِ جدید (باید در همین بازار یکتا باشد).
  @IsString()
  @IsNotEmpty()
  @MaxLength(100)
  newSerialNumber: string;

  // آخرین عددِ «کنتورِ قدیمی/خراب». فقط برای این است که مطمئن شویم مصرفِ دستگاهِ قدیمی کاملاً بل شده؛ روی
  // کنتورِ جدید «هیچ اثری ندارد». باید دقیقاً برابرِ آخرین قرائتِ بل‌شدهٔ کنتور (lastReading) باشد. اگر بیشتر است
  // (کنتور تا ۱۲۵۰ رفته ولی فقط تا ۱۰۰۰ بل شده)، اول بلِ نهایی را با currentReading=۱۲۵۰ و readingDate
  // (تاریخِ تعویض) صادر کنید و بعد تعویض کنید.
  @IsNumber()
  @Min(0)
  oldMeterFinalReading: number;

  // عددی که «کنتورِ جدید» هنگامِ نصب نشان می‌دهد؛ بل‌های بعدی از همین عدد حساب می‌شوند (قرائتِ بعدی − این عدد).
  // پیش‌فرض ۰ (دستگاهِ نو). اگر دستگاهِ جدید از قبل مثلاً ۱۰ نشان می‌دهد، ۱۰ بفرستید.
  @IsOptional()
  @IsNumber()
  @Min(0)
  newMeterInitialReading?: number;

  // تاریخِ تعویض (روز). پیش‌فرض امروز؛ نه در آینده و نه قبل از آخرین قرائت.
  @IsOptional()
  @IsDateString()
  replacedAt?: string;

  // دلیلِ تعویض اجباری است و در سابقهٔ تغییرات (audit log) ثبت می‌شود.
  @IsString()
  @IsNotEmpty()
  @MinLength(3)
  @MaxLength(500)
  reason: string;
}
