// نامِ ذخیره‌شده: فاصله‌های اضافه جمع می‌شود و دو سرِ نام تمیز می‌شود.
export const cleanName = (name: string) => name.replace(/\s+/g, ' ').trim();

// کلیدِ مقایسهٔ نام‌ها: «نذیر احمد»، «نذیراحمد» و «نذیر‌احمد» (نیم‌فاصله) و تفاوتِ ی/ي و ک/ك
// همه یک نام حساب می‌شوند — تا با تایپِ عجولانه دو دسته‌بندیِ تکراری ساخته نشود.
export const nameKey = (name: string) =>
  name
    .replace(/[\s‌‍]+/g, '')
    .replace(/ي/g, 'ی')
    .replace(/ك/g, 'ک')
    .toLowerCase();
